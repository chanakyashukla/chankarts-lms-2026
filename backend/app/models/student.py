import uuid
from datetime import datetime
from sqlalchemy import Column, String, DateTime, Date, ForeignKey, Enum, Boolean, Text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import relationship
from app.database import Base


class StudentStatus(str):
    ACTIVE = "active"
    INACTIVE = "inactive"
    SUSPENDED = "suspended"
    GRADUATED = "graduated"
    TRANSFERRED = "transferred"


class Student(Base):
    __tablename__ = "students"
    
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id"), unique=True, nullable=False)
    
    # CMA Registration ID: CMA-YYYY-#### (generated by database sequence)
    cma_registration_id = Column(String(20), unique=True, index=True, nullable=False)

    # Personalised portal route identifier, e.g. /academy/prakhyaat-verma.
    # This is a navigation convenience only — never an authorization mechanism.
    portal_slug = Column(String(120), unique=True, index=True, nullable=True)

    
    # Personal Information
    first_name = Column(String(100), nullable=False)
    last_name = Column(String(100), nullable=False)
    date_of_birth = Column(Date, nullable=True)  # nullable: not provided in source roster
    phone = Column(String(20))
    address = Column(Text)
    
    # Student Status
    status = Column(String(20), default=StudentStatus.ACTIVE, nullable=False)
    
    # Skill Level
    skill_level = Column(String(50))  # beginner, intermediate, advanced
    
    # Profile
    profile_image_url = Column(String(500))
    notes = Column(Text)
    
    # Profile Completeness (calculated)
    profile_complete = Column(Boolean, default=False)
    
    # Relationships
    user = relationship("User", back_populates="student_profile")
    guardians = relationship("Guardian", back_populates="student", cascade="all, delete-orphan")
    student_instruments = relationship("StudentInstrument", back_populates="student", cascade="all, delete-orphan")
    
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    
    @property
    def full_name(self) -> str:
        return f"{self.first_name} {self.last_name}"
    
    def calculate_profile_complete(self) -> bool:
        required_fields = [
            self.first_name,
            self.last_name,
            self.date_of_birth,
        ]
        has_instruments = len(self.student_instruments) > 0 if self.student_instruments else False
        return all(field is not None for field in required_fields) and has_instruments
